#!/usr/bin/env python3
"""Convert ASCII sprite sheets in assets/sprites/*.txt into a C++ header and preview PNGs.

Sprite format:
    @ name
    ..##..
    .#oo#.
    (blank line ends the sprite)

Pixel chars:  '#' ink   'o' forced clear   'w' pattern fill (wing; style chosen at draw time)
              '.' transparent
"""
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "assets" / "sprites"
HEADER = ROOT / "lib" / "okame_core" / "src" / "sprites.h"
PREVIEW = ROOT / "out" / "sprites"


def parse(path):
    sprites, name, rows = [], None, []

    def flush():
        if name is None:
            return
        if not rows:
            sys.exit(f"{path}: sprite {name} has no rows")
        w = max(len(r) for r in rows)
        sprites.append((name, [r.ljust(w, ".") for r in rows]))

    for line in path.read_text().splitlines():
        s = line.rstrip()
        if s.startswith("@"):
            flush()
            name, rows = s[1:].strip(), []
        elif not s or s.startswith(";"):
            if name is not None and rows:
                flush()
                name, rows = None, []
        elif name is not None:
            bad = set(s) - set("#ow.")
            if bad:
                sys.exit(f"{path}: sprite {name}: bad chars {bad}")
            rows.append(s)
    flush()
    return sprites


def pack(rows, chars):
    out = []
    for r in rows:
        for i in range(0, len(r), 8):
            b = 0
            for j, ch in enumerate(r[i:i + 8]):
                if ch in chars:
                    b |= 0x80 >> j
            out.append(b)
    return out


def emit(all_sprites):
    lines = [
        "// Generated by tools/gen_sprites.py from assets/sprites/*.txt. Do not edit.",
        "#pragma once",
        '#include "sprite.h"',
        "",
        "namespace spr {",
    ]
    for name, rows in all_sprites:
        w, h = len(rows[0]), len(rows)
        for suffix, chars in (("ink", "#"), ("mask", "#ow"), ("pat", "w")):
            data = pack(rows, chars)
            if suffix == "pat" and not any(data):
                continue
            body = ",".join(f"0x{b:02x}" for b in data)
            lines.append(f"inline const uint8_t {name}_{suffix}[] = {{{body}}};")
        has_pat = any(pack(rows, "w"))
        pat = f"{name}_pat" if has_pat else "nullptr"
        lines.append(f"inline const Sprite {name} = {{{w}, {h}, {name}_ink, {name}_mask, {pat}}};")
    lines += ["}  // namespace spr", ""]
    HEADER.parent.mkdir(parents=True, exist_ok=True)
    HEADER.write_text("\n".join(lines))


def preview(sheet_name, sprites):
    try:
        from PIL import Image, ImageDraw
    except ImportError:
        return
    scale, pad = 8, 2
    bg, ink, ghost, pat = (158, 170, 138), (30, 36, 24), (146, 158, 127), (70, 80, 60)
    cols = 6
    cell_w = max(len(r[0]) for _, r in sprites) + pad * 2
    cell_h = max(len(r) for _, r in sprites) + pad * 2 + 2
    nrows = (len(sprites) + cols - 1) // cols
    img = Image.new("RGB", (cols * cell_w * scale, nrows * cell_h * scale), bg)
    d = ImageDraw.Draw(img)
    for idx, (name, rows) in enumerate(sprites):
        ox = (idx % cols) * cell_w + pad
        oy = (idx // cols) * cell_h + pad
        for y in range(cell_h - pad * 2):
            for x in range(cell_w - pad * 2):
                ch = rows[y][x] if y < len(rows) and x < len(rows[0]) else "."
                c = {"#": ink, "w": pat}.get(ch, ghost)
                px, py = (ox + x) * scale, (oy + y) * scale
                d.rectangle([px, py, px + scale - 2, py + scale - 2], fill=c)
        d.text((ox * scale, (oy + cell_h - pad * 2 - 1) * scale), name, fill=(0, 0, 0))
    PREVIEW.mkdir(parents=True, exist_ok=True)
    img.save(PREVIEW / f"{sheet_name}.png")


def main():
    all_sprites, seen = [], set()
    for path in sorted(SRC.glob("*.txt")):
        sprites = parse(path)
        for name, _ in sprites:
            if name in seen:
                sys.exit(f"duplicate sprite name {name}")
            seen.add(name)
        all_sprites += sprites
        preview(path.stem, sprites)
    emit(all_sprites)
    print(f"{len(all_sprites)} sprites -> {HEADER.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
