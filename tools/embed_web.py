#!/usr/bin/env python3
"""Inline the menu icons into web/index.html, gzip it and emit src/web_assets.h (with the home-screen icon).

Also writes the built page to out/web/index.html for the mock server and screenshots.
"""
import gzip
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools"))
from gen_sprites import parse  # noqa: E402

icons = {name: rows for name, rows in parse(ROOT / "assets" / "sprites" / "icons.txt")}
# The friends card and the new-egg picker draw the visiting birds and each species from their real sprites.
icons.update({name: rows for name, rows in parse(ROOT / "assets" / "sprites" / "friends.txt") if not name.startswith("fr_wing")})
for sheet, want in (("bird.txt", "adult_idle"), ("budgie.txt", "budgie_adult_idle"), ("owl.txt", "owl_adult_idle")):
    icons.update({name: rows for name, rows in parse(ROOT / "assets" / "sprites" / sheet) if name == want})
# The bird shop, the outings and the family album (0.7).
icons.update({name: rows for name, rows in parse(ROOT / "assets" / "sprites" / "world.txt")
              if name.startswith("toy_") or name in ("pl_tree", "pl_cup", "pl_torii", "pl_mill_body", "pl_frites")})
icons.update({name: rows for name, rows in parse(ROOT / "assets" / "sprites" / "extras.txt") if name == "umbrella"})
html = (ROOT / "web" / "index.html").read_text()
html = html.replace("/*ICONS*/{}", json.dumps(icons, separators=(",", ":")))
tables = json.loads((ROOT / "assets" / "tables.json").read_text())
tables.pop("_comment", None)
html = html.replace("/*TABLES*/{}", json.dumps(tables, ensure_ascii=False, separators=(",", ":")))
import hashlib
page_hash = hashlib.sha256(html.encode()).hexdigest()[:12]
html = html.replace("/*PAGE*/\"dev\"", json.dumps(page_hash))
# The Content-Security-Policy names the final inline script by hash: nothing else can ever run on the page.
import base64, re as _re
scripts = _re.findall(r"<script>(.*?)</script>", html, _re.S)
assert len(scripts) == 1, "the page has one inline script"
script_hash = base64.b64encode(hashlib.sha256(scripts[0].encode()).digest()).decode()
CSP = (f"default-src 'self'; script-src 'sha256-{script_hash}'; style-src 'self' 'unsafe-inline'; "
       "img-src 'self' data: blob:; media-src 'self' data:; connect-src 'self'; frame-ancestors 'none'; base-uri 'none'")
(ROOT / "out" / "web").mkdir(parents=True, exist_ok=True)
(ROOT / "out" / "web" / "csp.txt").write_text(CSP)

built = ROOT / "out" / "web" / "index.html"
built.parent.mkdir(parents=True, exist_ok=True)
built.write_text(html)

data = gzip.compress(html.encode(), compresslevel=9, mtime=0)
body = ",".join(f"0x{b:02x}" for b in data)
icon = ",".join(f"0x{b:02x}" for b in (ROOT / "web" / "apple-touch-icon.png").read_bytes())
(ROOT / "src" / "web_assets.h").write_text(
    "// Generated by tools/embed_web.py from web/index.html. Do not edit.\n"
    "#pragma once\n#include <stdint.h>\n"
    f"static const uint8_t WEB_INDEX_GZ[] = {{{body}}};\n"
    f"static const uint8_t WEB_ICON_PNG[] = {{{icon}}};\n"
    f'#define WEB_PAGE_HASH "{page_hash}"\n'
    f'#define WEB_CSP "{CSP}"\n'
)
print(f"web: {len(html)} bytes -> {len(data)} gzipped")
